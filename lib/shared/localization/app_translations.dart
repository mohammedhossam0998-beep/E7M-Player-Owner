/// Lightweight translation layer (English <-> Arabic).
///
/// The English text itself is the key, so any string that is not in
/// [_ar] simply falls back to English (it never crashes or shows a key).
///
/// Usage:
///   Text('Start Date'.tr)
///   Text('{count} participants'.trArgs({'count': 12}))
class AppTranslations {
  AppTranslations._();

  static String _languageCode = 'en';

  static String get languageCode => _languageCode;
  static bool get isArabic => _languageCode == 'ar';

  /// Called by LanguageProvider whenever the language changes/loads.
  static void setLanguageCode(String code) => _languageCode = code;

  static String translate(String key) {
    if (!isArabic) return key;
    return _ar[key] ?? key;
  }

  static String translateArgs(String key, Map<String, Object?> args) {
    var text = translate(key);
    args.forEach((name, value) {
      text = text.replaceAll('{$name}', '${value ?? ''}');
    });
    return text;
  }

